package de.gigflow.backend;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.util.List;

/**
 * Idempotent, lightweight schema management.
 *
 * <p>Hibernate's {@code ddl-auto=update} scans and migrates the whole schema on every
 * startup, which on the free-tier Postgres can stall (lock contention / long DDL) and
 * delay the web server beyond the platform's port-scan timeout. Production therefore
 * runs with {@code ddl-auto=none} and relies on this initializer as the single source
 * of schema truth.</p>
 *
 * <p>Order: tables first (safe on a fresh DB), then columns added to already existing
 * tables (Hibernate's {@code ddl-auto} would not add those anyway).</p>
 */
@Component
@Order(0)
public class SchemaInitializer implements CommandLineRunner {

    private final JdbcTemplate jdbcTemplate;

    public SchemaInitializer(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(String... args) {
        apply(List.of(
                // --- Tables (idempotent; fresh-DB bootstrap) ---
                """
                create table if not exists bands (
                    id bigint generated by default as identity primary key,
                    name varchar(255) not null,
                    genre varchar(255)
                )
                """,
                """
                create table if not exists musicians (
                    id bigint generated by default as identity primary key,
                    first_name varchar(255) not null,
                    last_name varchar(255) not null,
                    instrument varchar(255),
                    email varchar(255) unique,
                    email_public boolean not null default false
                )
                """,
                """
                create table if not exists band_membership (
                    id bigint generated by default as identity primary key,
                    band_id bigint not null references bands (id),
                    musician_id bigint not null references musicians (id)
                )
                """,
                """
                create table if not exists events (
                    id bigint generated by default as identity primary key,
                    title varchar(255) not null,
                    date_time timestamp not null,
                    type varchar(31) not null,
                    band_id bigint not null references bands (id),
                    concert_id bigint references events (id),
                    panel_layout varchar(2000)
                )
                """,
                """
                create table if not exists event_participation (
                    id bigint generated by default as identity primary key,
                    event_id bigint not null references events (id),
                    musician_id bigint not null references musicians (id),
                    status varchar(31) not null
                )
                """,
                """
                create table if not exists event_location (
                    id bigint generated by default as identity primary key,
                    event_id bigint not null references events (id),
                    type varchar(31) not null,
                    name varchar(255) not null,
                    address varchar(255) not null,
                    note varchar(255),
                    phone varchar(255),
                    maps_url varchar(255)
                )
                """,
                """
                create table if not exists schedule_item (
                    id bigint generated by default as identity primary key,
                    event_id bigint not null references events (id),
                    label varchar(255) not null,
                    time time not null
                )
                """,
                """
                create table if not exists equipment (
                    id bigint generated by default as identity primary key,
                    name varchar(255) not null,
                    category varchar(255)
                )
                """,
                """
                create table if not exists equipment_requirement (
                    id bigint generated by default as identity primary key,
                    event_id bigint not null references events (id),
                    equipment_id bigint not null references equipment (id),
                    available_on_site varchar(20) not null default 'UNKNOWN',
                    needs_to_be_brought varchar(20) not null default 'UNKNOWN',
                    responsible_musician_id bigint references musicians (id)
                )
                """,
                """
                create table if not exists piece (
                    id bigint generated by default as identity primary key,
                    title varchar(255) not null,
                    sheet_pdf_path varchar(255),
                    sheet_pdf_original_name varchar(255),
                    demo_audio_path varchar(255),
                    demo_audio_original_name varchar(255),
                    youtube_url varchar(500)
                )
                """,
                """
                create table if not exists setlist (
                    id bigint generated by default as identity primary key,
                    event_id bigint not null unique references events (id)
                )
                """,
                """
                create table if not exists setlist_entry (
                    id bigint generated by default as identity primary key,
                    setlist_id bigint not null references setlist (id),
                    piece_id bigint not null references piece (id),
                    position integer not null
                )
                """,
                """
                create table if not exists users (
                    id bigint generated by default as identity primary key,
                    email varchar(255) not null unique,
                    password_hash varchar(255) not null,
                    organizer boolean not null default false,
                    musician_id bigint references musicians (id)
                )
                """,

                // --- Columns added to already existing tables (idempotent) ---
                "alter table musicians add column if not exists email_public boolean not null default false",
                "alter table musicians add column if not exists email varchar(255)",
                "alter table events add column if not exists panel_layout varchar(2000)",
                "alter table users add column if not exists organizer boolean not null default false",
                "alter table piece add column if not exists demo_audio_path varchar(255)",
                "alter table piece add column if not exists demo_audio_original_name varchar(255)",
                "alter table piece add column if not exists youtube_url varchar(500)",
                // Convert legacy boolean equipment columns to tri-state varchar values.
                "alter table equipment_requirement alter column available_on_site type varchar(20) using (case available_on_site when true then 'YES' else 'NO' end)",
                "alter table equipment_requirement alter column available_on_site set not null",
                "alter table equipment_requirement alter column available_on_site set default 'UNKNOWN'",
                "alter table equipment_requirement alter column needs_to_be_brought type varchar(20) using (case needs_to_be_brought when true then 'YES' else 'NO' end)",
                "alter table equipment_requirement alter column needs_to_be_brought set not null",
                "alter table equipment_requirement alter column needs_to_be_brought set default 'UNKNOWN'"
        ));
    }

    private void apply(List<String> statements) {
        for (String statement : statements) {
            try {
                jdbcTemplate.execute(statement);
            } catch (org.springframework.dao.DataAccessException ignored) {
                // Migration is best-effort; ignore pre-existing/failed states.
            }
        }
    }
}
